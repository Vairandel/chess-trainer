/**
 * The trap library. Every line here is checked by src/study/traps.test.ts with Stockfish:
 * the mistake really loses, the trap really wins, and the recommended moves really hold.
 */

/** A move in SAN and what it means. */
export type Step = [san: string, comment: string];

export interface Trap {
  id: string;
  group: 'your-openings' | 'classic';
  title: string;
  opening: string;
  /** The side you play in this chapter (board orientation). */
  you: 'w' | 'b';
  /** 'avoid': a trap you can fall into. 'set': a trap you can set for your opponent. */
  role: 'avoid' | 'set';
  summary: string;
  moves: Step[];
  /** Index in `moves` of the mistake that springs the trap. */
  mistake: number;
  /** What to play instead of the mistake (a variation starting at the same position). */
  instead: Step[];
  /** Other good moves at the mistake's position, accepted in "Test yourself". */
  alsoGood?: string[];
  dos: string[];
  donts: string[];
  /** Checked by the tests: who stands better at the end of the main line, by how much (pawns, or 'mate'). */
  check: { winner: 'w' | 'b'; atLeast: number | 'mate' };
}

